pipelineJob('03-distributed-multi-arch-matrix') {
    description('Concurrent distributed execution across multiple remote architectures to test load balancing & isolation')
    definition {
        cps {
            sandbox(true)
            script("""
pipeline {
    agent none
    stages {
        stage('Parallel Distributed Workloads') {
            parallel {
                stage('Branch A: Linux SSH Node') {
                    agent {
                        node {
                            label 'ssh'
                        }
                    }
                    stages {
                        stage('SSH Worker Task') {
                            steps {
                                echo "SSH Worker Task starting on \${env.NODE_NAME}"
                                sh 'echo "Node: \$(hostname) / Arch: \$(uname -m)"'
                                sh 'sleep 3'
                                echo 'SSH Task completed.'
                            }
                        }
                    }
                }
                stage('Branch B: Linux Inbound Node') {
                    agent {
                        node {
                            label 'inbound-agent'
                        }
                    }
                    stages {
                        stage('Inbound Worker Task') {
                            steps {
                                echo "Inbound Worker Task starting on \${env.NODE_NAME}"
                                sh 'echo "Node: \$(hostname) / Arch: \$(uname -m)"'
                                sh 'sleep 3'
                                echo 'Inbound Task completed.'
                            }
                        }
                    }
                }
            }
        }
        stage('Master Verification Summary') {
            agent {
                node {
                    label 'ssh || inbound-agent'
                }
            }
            steps {
                echo '=== Multi-Arch Remoting Matrix Completed Successfully ==='
                echo 'Both remote nodes processed tasks concurrently with complete isolation.'
            }
        }
    }
}
""".stripIndent())
        }
    }
}
