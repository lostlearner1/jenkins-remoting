// Job DSL definitions for Jenkins Remoting validation pipelines

pipelineJob('01-linux-ssh-build') {
    description('Test workload execution on remote Linux SSH Agent with isolated environment')
    definition {
        cps {
            sandbox(true)
            script("""
pipeline {
    agent {
        node {
            label 'ssh'
        }
    }
    stages {
        stage('Node Identification') {
            steps {
                echo '=== Executing on Remote SSH Agent ==='
                sh 'uname -a'
                sh 'whoami'
                sh 'pwd'
                sh 'java -version'
            }
        }
        stage('Environment Isolation Check') {
            steps {
                sh 'echo "Hostname: \$(hostname)"'
                sh 'echo "Current User ID: \$(id -u) (Group: \$(id -g))"'
            }
        }
        stage('Simulate Build Workload') {
            steps {
                sh 'mkdir -p build_output'
                sh 'date > build_output/build_info.txt'
                sh 'echo "Artifact generated by SSH Remoting Node" >> build_output/build_info.txt'
                sh 'cat build_output/build_info.txt'
            }
        }
    }
    post {
        success {
            echo 'SSH Node Execution Completed Successfully!'
        }
    }
}
""".stripIndent())
        }
    }
}

